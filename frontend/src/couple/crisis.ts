/** Имя блока — перечень контракта `PartnerMessage.withheld_crisis_blocks` (ни больше, ни меньше: `satisfies` выше). */
export type CrisisBlock = NonNullable<PartnerMessage["withheld_crisis_blocks"]>[number];

/** Перечень контракта (порядок — как в `api/openapi.yaml`). */
export const CRISIS_BLOCK_NAMES = Object.keys(CRISIS_BLOCKS) as CrisisBlock[];

/**
 * Набор блоков сервера (`withheld_crisis_blocks`) строго по контракту: непустой массив имён из перечня без повторов.
 * `null` — поля нет, оно null или нарушает контракт.
 *
 * Нарушение контракта в этом поле **не** делает ответ ленты «не по схеме» (`isCoupleFeed`), а откатывает протокол
 * этого сообщения на консервативный набор по `withheld_crisis`: отказ всей ленты скрыл бы помощь (и 112) под этим и
 * остальными остановленными сообщениями, а помощь при кризисе показывается при любом виде ответа (ТЗ §9.3, как
 * `parseDraftOutcome` и событие `crisis` чата). Неизвестное имя или повтор целиком отбрасывают набор, а не одно имя:
 * остаток мог быть собран для другого сочетания признаков, и показать его частично — показать не тот протокол.
 * Консервативный набор не содержит ни одного блока, который `crisis.respond` запрещает хоть при одном сочетании, —
 * значит, откат не показывает запрещённого блока и не теряет помощь.
 */
export function serverCrisisBlocks(v: unknown): CrisisBlock[] | null {
  if (!Array.isArray(v) || v.length === 0) return null;
  if (!v.every((b) => typeof b === "string" && Object.hasOwn(CRISIS_BLOCKS, b))) return null;
  if (new Set(v).size !== v.length) return null;
  return v as CrisisBlock[];
}

/**
 * Блоки под своим сообщением, остановленным безопасностью: набор сервера, если он есть и по контракту, иначе
 * (сообщения до миграции 0021, `null`, нарушение контракта) — консервативный набор по главному типу. Только для
 * своего (`outgoing`) сообщения со `withheld_reason: safety`; у полученного и при другой причине — пусто (поле
 * получателю не положено, пришедшее — игнорируется).
 */
export function withheldCrisisBlocks(m: PartnerMessage): { blocks: CrisisBlock[]; source: "server" | "conservative" } {
  if (m.direction !== "outgoing" || m.status !== "withheld" || m.withheld_reason !== "safety") return { blocks: [], source: "conservative" };
  const server = serverCrisisBlocks(m.withheld_crisis_blocks);
  return server ? { blocks: server, source: "server" } : { blocks: crisisBlocks(m.withheld_crisis), source: "conservative" };
}

/**
 * Консервативный набор блоков по главному типу (`withheld_crisis`) — для сообщений без набора сервера (до 0021,
 * АР-45, АР-57) и при нарушении контракта в наборе. У остановленного сообщения возможны признаки `threat_outgoing`,
 * `violence`, `self_harm`, `life_threat` в любом сочетании, а без набора клиент видит только главный. Для каждого
 * главного типа взяты блоки, которые `crisis.respond` не запрещает ни при одном сочетании с ним:
 * - нет `violence` («вина не на тебе») и `life_threat` («твоя жизнь в опасности») — при угрозе от автора
 *   (правило «А», R2-MAJOR-1) они обращены не к тому человеку; вместо них нейтральные `author_safety` /
 *   `author_safety_life`, которые сервер сам ставит автору при смешанном наборе;
 * - нет полного `outgoing_threat` и `outgoing_threat_mixed` («вернёмся к разговору, когда станет спокойнее») — при
 *   `self_harm` разговор не откладывается (R5-MAJOR-1); вместо них `outgoing_threat_brief`;
 * - `self_harm` — только при главном `self_harm`: сервер показывает его при этом признаке всегда;
 * - `author_safety_life` («немедленно звони») — только при главном `life_threat`;
 * - `not_sent` первым всегда: короткие блоки сами не говорят, что сообщение не ушло.
 * 112 и контакты помощи экран показывает под блоками всегда (`HelpContacts`).
 */
export function crisisBlocks(kind: PartnerMessage["withheld_crisis"] | undefined): ConservativeBlock[] {
  switch (kind) {
    case "threat_outgoing":
      return ["not_sent", "outgoing_threat_brief", "author_safety"];
    case "self_harm":
      return ["not_sent", "self_harm", "author_safety"];
    case "life_threat":
      return ["not_sent", "author_safety_life"];
    case "violence":
    default:
      return ["not_sent", "author_safety"];
  }
}

/** Блоки консервативного набора — без блоков, обращённых к пострадавшему, и без «вернёмся к разговору». */
export type ConservativeBlock = Exclude<CrisisBlock, "violence" | "life_threat" | "outgoing_threat" | "outgoing_threat_mixed">;
