/**
 * A8, Б-99 (коммит eb511b6) — граничные значения общей проверки `date-time` (RFC 3339, `api/openapi.yaml`) и `date`.
 * Дополняет `datetime.b99.test.ts` A4: несуществующие дни и время, пояса за пределами, пробелы, переводы строк,
 * не-ASCII цифры; допустимые по RFC 3339 вариации (строчные `t`/`z`, `-00:00`, длинная дробь, високосная секунда).
 */
import { toKbDocument } from "../admin/api";
import { isChatMessage } from "./chat";
import { isDateTime, isDay } from "./datetime";

const OK = [
  "2026-11-20t10:00:00z", // RFC 3339 §5.6: T и Z без учёта регистра
  "2026-11-20 10:00:00Z", // RFC 3339 §5.6, примечание: пробел вместо T
  "2026-12-31T23:59:60Z", // високосная секунда
  "2026-12-31T23:59:59.5-00:00", // неизвестный пояс
  "2026-11-20T10:00:00.1234567890123Z", // дробь любой длины
  "2028-02-29T00:00:00+14:00", // високосный год
  "0001-01-01T00:00:00Z",
];

const BAD = [
  "2026-02-29T10:00:00Z", // не високосный
  "2026-02-30T10:00:00Z",
  "2026-13-01T10:00:00Z",
  "2026-00-10T10:00:00Z",
  "2026-11-00T10:00:00Z",
  "0000-01-01T00:00:00Z", // года 0 нет
  "2026-11-20T24:00:00Z",
  "2026-11-20T10:60:00Z",
  "2026-11-20T10:00:61Z",
  "2026-11-20T10:00:00+24:00",
  "2026-11-20T10:00:00+03:60",
  "2026-11-20T10:00:00+0300", // пояс без двоеточия
  "2026-11-20T10:00:00+03", // пояс без минут
  "2026-11-20T10:00:00.Z", // дробь без цифр
  "2026-11-20T10:00:00,5Z", // запятая
  "2026-11-20T1:00:00Z",
  "26-11-20T10:00:00Z",
  "+002026-11-20T10:00:00Z", // расширенный год ECMAScript
  " 2026-11-20T10:00:00Z",
  "2026-11-20T10:00:00Z ",
  "2026-11-20T10:00:00Z\n",
  "2026-11-20T10:00:00ZZ",
  "2026-11-20T10:00:00UTC",
  "2026-11-20T10:00:00GMT+03:00",
  "２０２６-11-20T10:00:00Z", // полноширинные цифры
  "2026-11-20T10:00:00z+03:00",
];

describe("A8 · Б-99 · isDateTime — граничные значения", () => {
  test.each(OK)("принимает %s", (v) => expect(isDateTime(v)).toBe(true));
  test.each(BAD)("отвергает %j", (v) => expect(isDateTime(v)).toBe(false));
  test("не строки — нет", () => {
    for (const v of [new Date(), 0, NaN, [], ["2026-11-20T10:00:00Z"], { toString: () => "2026-11-20T10:00:00Z" }])
      expect(isDateTime(v)).toBe(false);
  });
});

describe("A8 · Б-99 · isDay — граничные значения", () => {
  test.each(["2026-11-20", "2028-02-29", "0001-01-01", "9999-12-31"])("принимает %s", (v) =>
    expect(isDay(v)).toBe(true),
  );
  test.each([
    "2026-02-29",
    "2026-04-31",
    "0000-01-01",
    "2026-1-01",
    "2026-11-20T00:00:00Z",
    " 2026-11-20",
    "2026-11-20\n",
    "20261120",
  ])("отвергает %j", (v) => expect(isDay(v)).toBe(false));
});

describe("A8 · Б-99 · чат: несуществующая дата отвергает реплику", () => {
  const base = {
    id: "c0000000-0000-4000-8000-000000000001",
    author: "owner",
    text: "Выдуманная реплика",
    created_at: "2026-11-20T10:00:00Z",
    client_message_id: null,
    reply_to: null,
    crisis: false,
  };
  test("контроль: годная реплика принимается", () => expect(isChatMessage(base)).toBe(true));
  test.each(["2026-02-30T10:00:00Z", "2026-11-20T25:00:00Z", "2026-11-20T10:00:00"])("%s — отказ", (created_at) =>
    expect(isChatMessage({ ...base, created_at })).toBe(false),
  );
});

describe("A8 · Б-99 · копии слабой проверки дат вне общего модуля (MINOR, вне объёма eb511b6)", () => {
  // Админ-клиент (АР-52) держит свою копию `Date.parse` — то, от чего Б-99 уводил чат: «1», «2026», «Nov 5» проходят
  // как `created_at` документа базы знаний (`format: date-time`). Строгий xfail: исправление переведёт тест в красный.
  const doc = {
    id: "d0000000-0000-4000-8000-000000000001",
    title: "Выдуманная книга",
    rights_basis: "license",
    index_status: "indexed",
    created_at: "2026-11-20T10:00:00Z",
  };
  test("контроль: годный документ принимается", () => expect(toKbDocument(doc)).not.toBeNull());
  test.fails("toKbDocument отвергает created_at «Nov 5» (ожидаемо по контракту; сейчас принимает)", () =>
    expect(toKbDocument({ ...doc, created_at: "Nov 5" })).toBeNull(),
  );
});
